
import { Job, TranscriptSegment, ChatMessage } from "../types";

const downloadFile = (content: string, fileName: string, contentType: string) => {
  const a = document.createElement("a");
  const file = new Blob([content], { type: contentType });
  a.href = URL.createObjectURL(file);
  a.download = fileName;
  a.click();
  URL.revokeObjectURL(a.href);
};

// --- Time Formatters ---

const formatTimeSRT = (seconds: number): string => {
  const date = new Date(0);
  date.setUTCMilliseconds(seconds * 1000);
  const iso = date.toISOString().substr(11, 12); // HH:MM:SS.mmm
  return iso.replace('.', ',');
};

const formatTimeSimple = (seconds: number): string => {
  const m = Math.floor(seconds / 60).toString().padStart(2, '0');
  const s = Math.floor(seconds % 60).toString().padStart(2, '0');
  return `[${m}:${s}]`;
};

// --- Export Functions ---

export const exportTranscriptAsSRT = (fileName: string, segments: TranscriptSegment[]) => {
  const srtContent = segments.map((seg, index) => {
    return `${index + 1}\n${formatTimeSRT(seg.start)} --> ${formatTimeSRT(seg.end)}\n${seg.text}\n`;
  }).join('\n');
  
  downloadFile(srtContent, `${fileName}.srt`, "text/plain");
};

export const exportTranscriptAsText = (fileName: string, segments: TranscriptSegment[], withTimestamps: boolean) => {
  const content = segments.map(seg => {
    const speaker = seg.speaker ? `${seg.speaker}: ` : '';
    const time = withTimestamps ? `${formatTimeSimple(seg.start)} ` : '';
    return `${time}${speaker}${seg.text}`;
  }).join('\n\n');

  downloadFile(content, `${fileName}_transcript.txt`, "text/plain");
};

export const exportPolishedContent = (fileName: string, content: string) => {
  downloadFile(content, `${fileName}_polished.md`, "text/markdown");
};

export const exportChatHistory = (fileName: string, messages: ChatMessage[]) => {
  const content = messages.map(msg => {
    const time = new Date(msg.timestamp).toLocaleString();
    const role = msg.role === 'user' ? 'User' : 'AI';
    return `[${time}] ${role}:\n${msg.text}\n`;
  }).join('\n' + '-'.repeat(20) + '\n\n');

  downloadFile(content, `${fileName}_chat_history.txt`, "text/plain");
};

export const exportSummaryAsMarkdown = (fileName: string, analysis: any) => {
  const { overview, topics, decisions, action_items } = analysis;
  
  const topicsSection = topics.map((t: any) => `### ${t.title}\n${t.content}`).join('\n\n');

  const md = `
# 會議記錄 (Meeting Minutes)
**來源檔名：** ${fileName}
**產出時間：** ${new Date().toLocaleString()}

---

## 1. 會議主旨 (Overview)
${overview}

## 2. 議題討論紀錄 (Topics)
${topicsSection}

## 3. 決議事項 (Decisions)
${decisions.length > 0 ? decisions.map((d: any) => `- ${d}`).join('\n') : '*無明確決議*'}

## 4. 待辦事項 (Action Items)
${action_items.length > 0 ? action_items.map((a: any) => `- [ ] ${a}`).join('\n') : '*無待辦事項*'}

---
*Generated by WhisperX & Gemini Hub*
  `.trim();
  
  downloadFile(md, `${fileName}_minutes.md`, "text/markdown");
};

